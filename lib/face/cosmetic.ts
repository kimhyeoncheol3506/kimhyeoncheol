export function cosmeticAdvice(f: FeatureScores, gender: "남" | "여", age: number): CosmeticTip[] {
  const adult = age >= 19;
  const picked = RULES.map((r) => ({ r, w: r.weak(f) }))
    .filter((x) => x.w > 0)
    .sort((a, b) => b.w - a.w)
    .slice(0, 4)
    .map(({ r }) => r.tip(gender));
  const tips: CosmeticTip[] = [...picked, ...BASICS(gender)];
  return tips.map((t) => (adult ? t : { ...t, procedure: undefined }));
}
