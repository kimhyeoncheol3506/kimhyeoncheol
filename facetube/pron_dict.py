_PAIRS = (("이", "가"), ("은", "는"), ("을", "를"), ("과", "와"), ("으로", "로"), ("이랑", "랑"), ("이라고", "라고"), ("이나", "나"), ("이에요", "예요"))


def _particle(last, rest):
    """약어를 한국어로 바꾸면 받침이 달라진다: 'Fed가' → '연준이', 'GDP는' → '지디피는'."""
    o = ord(last) - 0xAC00
    jong = o % 28 if 0 <= o < 11172 else 0
    for cons, vow in _PAIRS:
        for p in (cons, vow):
            if rest == p or (rest.startswith(p) and len(p) > 1):
                want = vow if jong == 0 or (p in ("으로", "로") and jong == 8) else cons
                return want + rest[len(p):]
    return rest


def spell_letters(word):
    return "".join(LETTER[c] for c in word.upper() if c in LETTER)


_ABBR_RE = None


def expand_abbr(t):
    """영문 약어를 읽는 말로. 사전에 없는 대문자 2~6글자 약어는 한 글자씩(GDP→지디피). 소문자 영어 낱말은 그대로."""
    global _ABBR_RE
    if _ABBR_RE is None:
        keys = sorted(ABBR, key=len, reverse=True)
        _ABBR_RE = re.compile(r"(?<![A-Za-z])(" + "|".join(re.escape(k) for k in keys) + r")(?![A-Za-z])")
    t = _ABBR_RE.sub(lambda m: ABBR[m.group(1)] + "\0", t)
    t = re.sub(r"(?<![A-Za-z])([A-Z]{2,6})(?![A-Za-z])", lambda m: spell_letters(m.group(1)) + "\0", t)
    t = re.sub("([가-힣])\0([가-힣]+)?", lambda m: m.group(1) + _particle(m.group(1), m.group(2) or ""), t)
    t = t.replace("\0", "")
    t = re.sub(r"(?<![A-Za-z])([A-Z])(?=[-\s]?[가-힣\d])", lambda m: LETTER[m.group(1)], t)      # K-반도체, A씨
    t = re.sub(r"([가-힣])-(?=[가-힣])", r"\1 ", t)                                                # 케이-반도체 → 케이 반도체
    return t


