def tok(kind, v):
    if kind == "p":
        n = int(v); return sino(n) + " 원", f"{n:,}원"
    if kind == "pc":
        x = float(v); i = int(round(x)); return sino(i) + " 퍼센트", f"{i}%"
    if kind == "k":
        n = int(v); return sino(n) + " 킬로그램", f"{n:,}kg"
    if kind == "w":
        m, k = map(int, v.split("-")); return f"{MKR[m]} {ORD[k]} 주", f"{m}월 {k}주"
    if kind == "y":
        return sino(int(v)) + "년", f"{v}년"
    if kind == "n":  # 그냥 수
        return sino(int(v)), v
    raise ValueError(kind)


