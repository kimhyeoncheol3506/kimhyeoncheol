from pronounce import sino as _s
sino = lambda n: _s(int(n))
DIG = "영일이삼사오육칠팔구"


def dec(v):  # 6.31 → 육 점 삼 일
    a, _, b = v.partition(".")
    return sino(int(a)) + (" 점 " + " ".join(DIG[int(c)] for c in b) if b else "")


def won(n):  # 천 원 단위 반올림
    r = int(n / 1000 + 0.5); m, k = divmod(r, 10)
    if k == 0: raise ValueError(f"딱 떨어지는 만 단위는 음성 오인식 위험: {n}")
    tts = (sino(m * 10000) + " " if m else "") + sino(k * 1000) + " 원"
    sub = (f"{m}만 " if m else "") + f"{k}천 원"
    return tts.replace("  ", " "), sub


def mi(v):
    if "/" in v:
        a, b = v.split("/"); return f"{sino(int(a))}에서 {sino(int(b))} 미", f"{v}미"
    return f"{sino(int(v))} 미", f"{v}미"


def tok(kind, v):
    if kind == "p": return won(int(v))
    if kind == "e": n = int(v); return sino(n) + " 원", f"{n:,}원"
    if kind == "x": return dec(v) + " 배", f"{v}배"
    if kind == "pc": return sino(int(v)) + " 퍼센트", f"{v}%"
    if kind == "t": return dec(v) + " 톤", (f"{int(v):,}" if "." not in v else v) + "톤"
    if kind == "mi": return mi(v)
    if kind == "g": return sino(int(v)) + " 그램", f"{v}g"
    if kind == "c": n = int(v); return sino(n) + " 건", f"{n:,}건"
    if kind == "y": return sino(int(v)) + "년", f"{v}년"
    if kind == "n": return sino(int(v)), v
    raise ValueError(kind)


