def S(text, **sig):
    tts = re.sub(r"\{(\w+):([^}]+)\}", lambda m: tok(m.group(1), m.group(2))[0], text)
    sub = re.sub(r"\{(\w+):([^}]+)\}", lambda m: tok(m.group(1), m.group(2))[1], text)
    for a, b in SUBFIX: sub = sub.replace(a, b)
    return [tts, sig, sub]


